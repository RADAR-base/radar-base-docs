import path from 'node:path';
import {docIdFor, slugifyPath} from './markdown.mjs';

/**
 * Turns the `sidebar:` block of a project's radar-docs.yml into a Docusaurus sidebar.
 *
 * Maintainers refer to their own files the way they wrote them ("Quickstart.md"), so
 * entries are matched against the original path, the slugified path and the bare
 * filename. Anything published but not listed is appended, so adding a file to a repo
 * never makes it invisible.
 */
export function buildSidebar({manifestSidebar, docs, pinned = []}) {
  const byKey = new Map();
  for (const doc of docs) {
    for (const key of [doc.relPath, doc.slugPath, doc.docId, path.posix.basename(doc.relPath)]) {
      if (key && !byKey.has(key)) byKey.set(key, doc);
    }
  }

  const used = new Set();
  const missing = [];

  const lookup = (entry) => {
    const candidates = [entry, slugifyPath(entry), docIdFor(slugifyPath(entry)), path.posix.basename(entry)];
    for (const candidate of candidates) {
      const doc = byKey.get(candidate);
      if (doc) return doc;
    }
    return null;
  };

  const convert = (entries) =>
    entries.flatMap((entry) => {
      if (typeof entry === 'string') {
        const doc = lookup(entry);
        if (!doc) {
          missing.push(entry);
          return [];
        }
        used.add(doc.docId);
        return [doc.docId];
      }

      if (entry && typeof entry === 'object' && Array.isArray(entry.items)) {
        const items = convert(entry.items);
        if (items.length === 0) return [];
        return [
          {
            type: 'category',
            label: entry.label ?? 'Untitled',
            collapsed: entry.collapsed ?? true,
            items,
          },
        ];
      }

      missing.push(JSON.stringify(entry));
      return [];
    });

  const listed = Array.isArray(manifestSidebar) ? convert(manifestSidebar) : [];

  // Pages the manifest did not mention are appended alphabetically, except for any
  // the caller pinned — the auto-published README belongs at the top, not under "o".
  const remaining = docs
    .filter((doc) => !used.has(doc.docId))
    .sort((a, b) => {
      const rank = (doc) => (pinned.includes(doc.docId) ? pinned.indexOf(doc.docId) : pinned.length);
      return rank(a) - rank(b) || a.docId.localeCompare(b.docId);
    })
    .map((doc) => doc.docId);

  const items = [...listed, ...remaining];
  return {
    sidebar: {docs: items.length > 0 ? items : [{type: 'autogenerated', dirName: '.'}]},
    missing,
  };
}
